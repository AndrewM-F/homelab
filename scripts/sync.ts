#!/usr/bin/env bun
/**
 * Publishes the private inventory to the places that need it.
 *
 *   inventory.local.json  →  .dev.vars                 (local `bun run dev`)
 *                         →  Worker secret  INVENTORY_JSON  (with --push)
 *                         →  collector/config.json        (probes + connect pages)
 *
 * Nothing private is written anywhere tracked by git. `.dev.vars` and
 * `collector/config.json` are both ignored.
 *
 *   bun run sync            validate + write local files
 *   bun run sync --push     also upload the Worker secret
 *   bun run sync --install  also copy the collector to the given host
 */

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'
import { parseInventory } from '../src/lib/inventory'

const ROOT = join(import.meta.dir, '..')
const LOCAL = join(ROOT, 'inventory.local.json')
const DEV_VARS = join(ROOT, '.dev.vars')
const COLLECTOR_CONFIG = join(ROOT, 'collector', 'config.json')

const args = new Set(process.argv.slice(2))
const push = args.has('--push')
const installTarget = [...args].find((arg) => arg.startsWith('--install='))?.split('=')[1]

function die(message: string): never {
  console.error(`sync: ${message}`)
  process.exit(1)
}

if (!existsSync(LOCAL)) die(`missing ${LOCAL} — copy inventory.example.json and edit it`)

let inventory
try {
  inventory = parseInventory(JSON.parse(readFileSync(LOCAL, 'utf8')))
} catch (error) {
  die(error instanceof Error ? error.message : String(error))
}

// ---------------------------------------------------------------- checks

const warnings: string[] = []
for (const service of inventory.services) {
  if (!service.origin && !service.connect) {
    warnings.push(`${service.slug}: no origin and no connect block — the tunnel will skip it`)
  }
  if (service.connect && !service.connect.command) {
    warnings.push(`${service.slug}: connect without a command — the page will look empty`)
  }
  if (service.probeUrl && service.probeUrl.includes('localhost')) {
    warnings.push(`${service.slug}: probe points at localhost, which the collector cannot reach`)
  }
}

// ---------------------------------------------------------- local dev env

const devVars = [
  `# generated by scripts/sync.ts — do not commit`,
  `INVENTORY_JSON=${JSON.stringify(inventory)}`,
  `STATS_URL=${process.env.STATS_URL ?? 'http://127.0.0.1:9101/stats'}`,
  `CF_ACCESS_CLIENT_ID=${process.env.CF_ACCESS_CLIENT_ID ?? ''}`,
  `CF_ACCESS_CLIENT_SECRET=${process.env.CF_ACCESS_CLIENT_SECRET ?? ''}`,
  '',
].join('\n')
writeFileSync(DEV_VARS, devVars, 'utf8')

// ------------------------------------------------------ collector config

const collectorConfig = {
  listen: { host: '0.0.0.0', port: 9101 },
  interface: 'vmbr0',
  disks: ['/', '/var/lib/vz'],
  probes: inventory.services
    .filter((service) => service.probeUrl)
    .map((service) => ({ slug: service.slug, url: service.probeUrl })),
  root_connect: inventory.services.find((service) => service.connect)?.slug,
  connect: inventory.services
    .filter((service) => service.connect)
    .map((service) => ({
      slug: service.slug,
      name: service.name,
      description: service.description ?? service.connect!.protocol.toUpperCase(),
      protocol: service.connect!.protocol,
      address: service.connect!.address,
      command: service.connect!.command ?? '',
    })),
}
writeFileSync(COLLECTOR_CONFIG, JSON.stringify(collectorConfig, null, 2) + '\n', 'utf8')

// ----------------------------------------------------------------- report

const tunnelHosts = inventory.services.filter((service) => service.origin)
const connectHosts = inventory.services.filter((service) => service.connect)

console.log(`sync: ${inventory.services.length} services across ${inventory.machines.length} machines`)
console.log(`      ${tunnelHosts.length} tunnel hostnames, ${connectHosts.length} connect pages`)
console.log(`      wrote ${DEV_VARS.replace(ROOT + '/', '')}`)
console.log(`      wrote ${COLLECTOR_CONFIG.replace(ROOT + '/', '')}`)
for (const warning of warnings) console.warn(`      warn: ${warning}`)

// ------------------------------------------------------------------- push

async function wrangler(argv: string[], stdin?: string): Promise<number> {
  const proc = Bun.spawn(['bunx', 'wrangler', ...argv], {
    cwd: ROOT,
    stdin: stdin ? new Blob([stdin]) : 'ignore',
    stdout: 'inherit',
    stderr: 'inherit',
  })
  return proc.exited
}

if (push) {
  const secrets: [string, string][] = [
    ['INVENTORY_JSON', JSON.stringify(inventory)],
    ['STATS_URL', process.env.STATS_URL ?? ''],
    ['CF_ACCESS_CLIENT_ID', process.env.CF_ACCESS_CLIENT_ID ?? ''],
    ['CF_ACCESS_CLIENT_SECRET', process.env.CF_ACCESS_CLIENT_SECRET ?? ''],
  ].filter((entry): entry is [string, string] => Boolean(entry[1]))

  if (secrets.length === 0) die('nothing to push — set the STATS_URL / Access token env vars first')

  for (const [name, value] of secrets) {
    process.stdout.write(`      pushing secret ${name} … `)
    const code = await wrangler(['secret', 'put', name], value)
    if (code !== 0) die(`wrangler secret put ${name} failed`)
    console.log('ok')
  }
}

if (installTarget) {
  console.log(`      installing collector on ${installTarget}`)
  const code = await Bun.spawn(
    [
      'ssh',
      installTarget,
      'install -m 0755 /dev/stdin /usr/local/sbin/homelab-collector.py && ' +
        'install -m 0644 /dev/null /etc/homelab-collector.json',
    ],
    { stdin: Bun.file(join(ROOT, 'collector', 'homelab-collector.py')), stdout: 'inherit', stderr: 'inherit' },
  ).exited
  if (code !== 0) die('collector install failed')
}

process.exit(0)
